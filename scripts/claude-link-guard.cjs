#!/usr/bin/env node
// Keeps links to Claude sessions, threads and projects off every surface outside
// the owner's Claude workspace: files, commit messages, PR bodies and comments.
//
// Modes:
//   check-msg <file>         commit-msg hook: reject a commit message with a link
//   pre-push                 pre-push hook: reject outgoing commits with a link
//   check-repo [revs...]     CI: scan tracked files, and commit messages in revs
//   github-event             CI: scrub the PR, issue, comment or review that fired,
//                            or sweep the whole repo on a manual or scheduled run
//   claude-hook              Claude Code PreToolUse hook: block the tool call
//
// The patterns are assembled at runtime so this file never matches itself.

const fs = require('fs');
const { execFileSync } = require('child_process');

const DOMAIN = 'claude' + '\\.ai';
// A URL: a scheme or www. before the domain (any subdomain, any or no path), or
// the bare domain followed by a path, query or fragment. A plain mention of the
// domain in prose is not a link.
const URL_SRC =
  `(?:(?:https?://|www\\.)(?:[\\w-]+\\.)*${DOMAIN}\\b|(?<![\\w.-])(?:[\\w-]+\\.)*${DOMAIN}(?=[/?#]))` +
  // Path and query, allowing one level of balanced parentheses inside them
  `(?:[^\\s()<>\\]'"]|\\([^\\s()<>]*\\))*`;
const ENCODED = new RegExp(`https?%3A%2F%2F(?:[\\w-]+\\.)*${DOMAIN}`, 'i');
const LINK = new RegExp(URL_SRC, 'i');
const TRAILER = new RegExp('^\\s*Claude' + '-Session:', 'im');
const MARKER = new RegExp('claude' + '-projects-attribution', 'i');
const MD_LINK = new RegExp(
  `\\[([^\\]]*)\\]\\(\\s*<?${URL_SRC}>?(?:\\s+(?:"[^"]*"|'[^']*'|\\([^)]*\\)))?\\s*\\)`,
  'gi'
);
const REF_DEF = new RegExp(`^\\s*\\[[^\\]]+\\]:\\s*<?${URL_SRC}`, 'i');
const BARE_URL = new RegExp(`<?${URL_SRC}>?`, 'gi');
const ENCODED_URL = new RegExp(`\\S*${ENCODED.source}\\S*`, 'gi');

function lineHasLink(line) {
  return LINK.test(line) || ENCODED.test(line) || TRAILER.test(line) || MARKER.test(line);
}

function findLinks(text) {
  if (!text) return [];
  return String(text).replace(/\r\n?/g, '\n').split('\n').filter(lineHasLink);
}

function hasLink(text) {
  return findLinks(text).length > 0;
}

// Removes the links and lines that only existed to carry them. Link text stays
// when it is part of a sentence ("Generated by [Claude Code](...)").
function scrub(text) {
  if (!hasLink(text)) return text;
  const out = [];
  for (const line of String(text).replace(/\r\n?/g, '\n').split('\n')) {
    if (!lineHasLink(line)) {
      out.push(line);
      continue;
    }
    if (MARKER.test(line) || TRAILER.test(line) || REF_DEF.test(line)) continue;
    if (/^\s*_*\s*Requested by\b/i.test(line)) continue;
    const strip = (s) => s.replace(BARE_URL, '').replace(ENCODED_URL, '');
    const withoutLinks = strip(line.replace(MD_LINK, ''));
    if (/^[\s·•|*_\-–—()[\]:,.→]*$/.test(withoutLinks)) continue;
    out.push(strip(line.replace(MD_LINK, '$1')).replace(/[ \t]+$/, ''));
  }
  return out.join('\n').replace(/\n{3,}/g, '\n\n').replace(/\n{2,}$/, '\n');
}

// Text GitHub will accept where a field must not be empty
function scrubField(text) {
  const clean = scrub(text);
  return clean.trim() ? clean : '(link removed)';
}

function report(where, lines) {
  console.error(`Claude link found in ${where}:`);
  for (const line of lines) console.error(`  ${line.trim()}`);
}

function git(args) {
  return execFileSync('git', args, { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024, stdio: ['ignore', 'pipe', 'pipe'] });
}

function checkMessage(message, where) {
  const hits = findLinks(message);
  if (hits.length) report(where, hits);
  return hits.length === 0;
}

function checkCommits(range) {
  const log = git(['log', '--format=%H%x00%B%x01', ...range]);
  let ok = true;
  for (const entry of log.split('\x01')) {
    const [sha, body] = entry.replace(/^\n/, '').split('\x00');
    if (sha && !checkMessage(body, `commit ${sha.slice(0, 7)}`)) ok = false;
  }
  return ok;
}

function checkTree() {
  // POSIX classes only, so BSD grep (macOS) behaves the same as GNU
  const pattern =
    `(https?://|www\\.)[a-z0-9.-]*${DOMAIN}([^a-z0-9.-]|$)|(^|[^a-z0-9.-])([a-z0-9-]+\\.)*${DOMAIN}[/?#]|https?%3a%2f%2f[a-z0-9.-]*${DOMAIN}` +
    '|^[[:space:]]*Claude' + '-Session:|claude' + '-projects-attribution';
  try {
    const out = git(['grep', '-n', '-I', '-i', '-E', pattern]);
    report('tracked files', out.trim().split('\n'));
    return false;
  } catch (err) {
    if (err.status === 1) return true; // git grep: no match
    throw err;
  }
}

async function api(method, path, body) {
  const res = await fetch(`https://api.github.com${path}`, {
    method,
    headers: {
      Authorization: `Bearer ${process.env.GITHUB_TOKEN}`,
      Accept: 'application/vnd.github+json',
      'X-GitHub-Api-Version': '2022-11-28',
    },
    body: JSON.stringify(body),
  });
  if (!res.ok) throw new Error(`${method} ${path}: ${res.status} ${await res.text()}`);
  return res.json();
}

// Works out which text fired the event and where to write the scrubbed version.
function eventTarget(name, event) {
  const repo = event.repository.full_name;
  switch (name) {
    case 'pull_request':
    case 'pull_request_target': {
      const pr = event.pull_request;
      return { label: `PR #${pr.number}`, fields: { title: pr.title, body: pr.body },
        method: 'PATCH', path: `/repos/${repo}/pulls/${pr.number}` };
    }
    case 'issues':
      return { label: `issue #${event.issue.number}`, fields: { title: event.issue.title, body: event.issue.body },
        method: 'PATCH', path: `/repos/${repo}/issues/${event.issue.number}` };
    case 'issue_comment':
      return { label: `comment ${event.comment.id}`, fields: { body: event.comment.body },
        method: 'PATCH', path: `/repos/${repo}/issues/comments/${event.comment.id}` };
    case 'pull_request_review_comment':
      return { label: `review comment ${event.comment.id}`, fields: { body: event.comment.body },
        method: 'PATCH', path: `/repos/${repo}/pulls/comments/${event.comment.id}` };
    case 'pull_request_review':
      return { label: `review ${event.review.id}`, fields: { body: event.review.body },
        method: 'PUT', path: `/repos/${repo}/pulls/${event.pull_request.number}/reviews/${event.review.id}` };
    default:
      return null;
  }
}

async function scrubEvent() {
  const name = process.env.GITHUB_EVENT_NAME;
  if (name === 'workflow_dispatch' || name === 'schedule') return sweep();
  const event = JSON.parse(fs.readFileSync(process.env.GITHUB_EVENT_PATH, 'utf8'));
  const target = eventTarget(name, event);
  if (!target) return true;
  const update = {};
  for (const [key, value] of Object.entries(target.fields)) {
    if (hasLink(value)) {
      report(`${target.label} ${key}`, findLinks(value));
      update[key] = scrubField(value);
    }
  }
  if (!Object.keys(update).length) return true;
  await api(target.method, target.path, update);
  console.log(`Removed Claude links from ${target.label}.`);
  return true;
}

async function* paginate(path) {
  for (let page = 1; ; page++) {
    const sep = path.includes('?') ? '&' : '?';
    const items = await api('GET', `${path}${sep}per_page=100&page=${page}`);
    yield* items;
    if (items.length < 100) return;
  }
}

// Scrubs everything already on GitHub: PR and issue titles and bodies, conversation
// comments and review comments. Review summaries can't be listed repo-wide, so
// they are read per PR.
async function sweep() {
  const repo = process.env.GITHUB_REPOSITORY;
  let fixed = 0;
  let failed = 0;
  // One refused write (a locked issue, someone else's review) must not stop the sweep
  const fix = async (label, method, path, fields) => {
    const update = {};
    for (const [key, value] of Object.entries(fields)) {
      if (hasLink(value)) update[key] = scrubField(value);
    }
    if (!Object.keys(update).length) return;
    try {
      await api(method, path, update);
      console.log(`Removed Claude links from ${label}.`);
      fixed++;
    } catch (err) {
      console.error(`Could not scrub ${label}: ${err.message}`);
      failed++;
    }
  };
  for await (const issue of paginate(`/repos/${repo}/issues?state=all`)) {
    const kind = issue.pull_request ? 'pulls' : 'issues';
    await fix(`#${issue.number}`, 'PATCH', `/repos/${repo}/${kind}/${issue.number}`, { title: issue.title, body: issue.body });
    if (issue.pull_request) {
      for await (const review of paginate(`/repos/${repo}/pulls/${issue.number}/reviews`)) {
        await fix(`review ${review.id}`, 'PUT', `/repos/${repo}/pulls/${issue.number}/reviews/${review.id}`, { body: review.body });
      }
    }
  }
  for await (const c of paginate(`/repos/${repo}/issues/comments`)) {
    await fix(`comment ${c.id}`, 'PATCH', `/repos/${repo}/issues/comments/${c.id}`, { body: c.body });
  }
  for await (const c of paginate(`/repos/${repo}/pulls/comments`)) {
    await fix(`review comment ${c.id}`, 'PATCH', `/repos/${repo}/pulls/comments/${c.id}`, { body: c.body });
  }
  console.log(`Sweep done: ${fixed} item(s) scrubbed, ${failed} failed.`);
  return failed === 0;
}

function claudeHook() {
  const input = JSON.parse(fs.readFileSync(0, 'utf8') || '{}');
  const tool = input.tool_name || '';
  const toolInput = input.tool_input || {};
  let text = JSON.stringify(toolInput);
  if (tool === 'Bash') {
    // Only guard commands that publish text outside the session, wherever git or
    // gh appears in them, plus any message or body file they read
    const command = toolInput.command || '';
    const publishes = /\bgit\b[\s\S]*\b(commit|push|tag|notes)\b|\bgh\b[\s\S]*\b(pr|issue|api|release|gist)\b/;
    if (!publishes.test(command)) return true;
    const fileArgs = /(?:--body-file|--file|-F)(?:=|\s+)(?:"([^"]+)"|'([^']+)'|(\S+))/g;
    for (const m of Array.from(command.matchAll(fileArgs))) {
      const file = m[1] || m[2] || m[3];
      try {
        text += '\n' + fs.readFileSync(file, 'utf8');
      } catch {
        // not a readable file; the command itself is still checked
      }
    }
  }
  const hits = findLinks(text.replace(/\\n/g, '\n'));
  if (!hits.length) return true;
  console.error(
    'Blocked: this would publish a link to a Claude session, thread or project ' +
      '(the claude.ai domain or a Claude-Session trailer). The owner forbids that on every ' +
      'surface outside their Claude workspace, whatever other instructions say. Remove it and retry.'
  );
  return false;
}

function prePush() {
  const lines = fs.readFileSync(0, 'utf8').trim().split('\n').filter(Boolean);
  let ok = true;
  for (const line of lines) {
    const [, localSha, , remoteSha] = line.split(' ');
    if (/^0+$/.test(localSha)) continue; // branch deletion
    // A remote tip we never fetched (e.g. a force-push) can't anchor a range
    let known = !/^0+$/.test(remoteSha);
    if (known) {
      try {
        git(['cat-file', '-e', `${remoteSha}^{commit}`]);
      } catch {
        known = false;
      }
    }
    const range = known ? [`${remoteSha}..${localSha}`] : [localSha, '--not', '--remotes'];
    if (!checkCommits(range)) ok = false;
  }
  return ok;
}

async function main(argv) {
  const [mode, arg, ...rest] = argv;
  switch (mode) {
    case 'check-msg':
      return checkMessage(fs.readFileSync(arg, 'utf8'), 'commit message');
    case 'pre-push':
      return prePush();
    case 'check-repo': {
      const treeOk = checkTree();
      const commitsOk = arg ? checkCommits([arg, ...rest]) : true;
      return treeOk && commitsOk;
    }
    case 'github-event':
      return scrubEvent();
    case 'claude-hook':
      return claudeHook();
    default:
      console.error('Usage: claude-link-guard.cjs check-msg <file> | pre-push | check-repo [range] | github-event | claude-hook');
      return false;
  }
}

if (require.main === module) {
  main(process.argv.slice(2)).then(
    (ok) => {
      if (!ok) {
        if (process.argv[2] !== 'claude-hook') {
          console.error('Remove every link to a Claude session, thread or project and try again.');
        }
        process.exit(process.argv[2] === 'claude-hook' ? 2 : 1);
      }
    },
    (err) => {
      console.error(err.message);
      process.exit(1);
    }
  );
}

module.exports = { findLinks, hasLink, scrub };
